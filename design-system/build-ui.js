// Syncs the Ant Design tokens into the Streamlit app (LIGHT MODE ONLY for now).
//   node build-ui.js
// Writes:
//   ../.streamlit/config.toml  Streamlit theme, values taken from Ant tokens
//   ../ui/app.css              bundle = used --ant-* vars + spacing.css + ui/components.css
// Where an Ant default fails WCAG AA, we pick the nearest Ant palette step that passes
// and record it in the report below. Nothing here is hand-typed color.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens', f), 'utf8'));
// A Windows checkout has CRLF line endings, and the token parsing below looks for plain newlines. Without
// this it finds no tokens and writes an app.css with none of its variables defined.
const readText = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const g = read('global.light.json');
const palettes = read('palettes.json');

// ---------- color helpers ----------
const hex = (n) => Math.round(n).toString(16).padStart(2, '0');
const parse = (c) => {
  if (c.startsWith('#')) {
    const h = c.length === 4 ? [...c.slice(1)].map((x) => x + x).join('') : c.slice(1, 7);
    return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).concat(c.length > 7 ? parseInt(c.slice(7, 9), 16) / 255 : 1);
  }
  const m = c.match(/rgba?\(([^)]+)\)/);
  const [r, b, bl, a = 1] = m[1].split(',').map(Number);
  return [r, b, bl, a];
};
const solid = (c, bg = '#ffffff') => {
  const [r, gg, b, a] = parse(c);
  const [br, bg_, bb] = parse(bg);
  return '#' + [r * a + br * (1 - a), gg * a + bg_ * (1 - a), b * a + bb * (1 - a)].map(hex).join('');
};
const lum = (c) => {
  const [r, gg, b] = parse(solid(c)).slice(0, 3).map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * gg + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
// First candidate that meets `min` against every background, else the strongest one.
const pick = (cands, bgs, min) =>
  cands.find((c) => bgs.every((b) => contrast(c, b) >= min)) || cands[cands.length - 1];

const report = [];
const bgPage = solid(g.colorBgContainer);
const step = (name, i) => palettes[name].light[i];

// ---------- chosen values ----------
const text = solid(g.colorText);
const primaryCands = [g.colorPrimary, g.colorPrimaryActive];
const primary = pick(primaryCands, [bgPage], 4.5); // white-on-primary button label AND link text
if (primary !== g.colorPrimary)
  report.push(`primary ${g.colorPrimary} -> ${primary} (white text on ${g.colorPrimary} is ${contrast('#ffffff', g.colorPrimary).toFixed(2)}:1, needs 4.5)`);
const border = solid(g.colorTextTertiary); // 3:1 UI boundary
report.push(`widget border ${g.colorBorder} (${contrast(g.colorBorder, bgPage).toFixed(2)}:1) -> ${border} (${contrast(border, bgPage).toFixed(2)}:1), needs 3:1; cards keep colorBorderSecondary via CSS`);

// status hues: Ant 6 -> 7 -> 8 until text passes 4.5 on white AND on its own tint
const hue = (name, bgTint) => pick([5, 6, 7, 8].map((i) => step(name, i)), [bgPage, bgTint], 4.5);
const hues = {
  red: [hue('red', g.colorErrorBg), g.colorErrorBg],
  orange: [hue('orange', step('orange', 0)), step('orange', 0)],
  yellow: [hue('gold', g.colorWarningBg), g.colorWarningBg],
  blue: [hue('blue', g.colorInfoBg), g.colorInfoBg],
  green: [hue('green', g.colorSuccessBg), g.colorSuccessBg],
  violet: [hue('purple', step('purple', 0)), step('purple', 0)],
  gray: [solid(g.colorTextSecondary), g.colorBgLayout],
};

const px = (n) => `${n}px`;
const rem = (n) => `${+(n / 16).toFixed(4)}rem`;
const font = g.fontFamily.replace(/['"]/g, '').replace(/\s+/g, ' ');

const toml = `# GENERATED by design-system/build-ui.js from Ant Design v6 tokens. Edit the generator, not this file.
# Light mode only for now (design-system keeps dark tokens for later).
[browser]
# No usage telemetry (privacy) and nothing written to the home dir (read-only on Vercel).
gatherUsageStats = false

[client]
# Hide Streamlit's developer toolbar (Deploy button, rerun/settings menu) everywhere, not just in production.
toolbarMode = "minimal"

[server]
# Serves ./static at /app/static (vendored GSAP + landing.js).
enableStaticServing = true

[theme]
base = "light"
primaryColor = "${text}"  # ink, not Ant blue: checkboxes, focus and radios follow the near-black brand
backgroundColor = "${bgPage}"
secondaryBackgroundColor = "${solid(g.colorBgLayout)}"
textColor = "${text}"
linkColor = "${primary}"
font = "Inter"
codeFont = "JetBrains Mono"
baseFontSize = ${g.fontSizeLG}
baseRadius = "none"
buttonRadius = "none"
borderColor = "${border}"
showWidgetBorder = true
headingFontSizes = ["${rem(g.fontSizeHeading2)}", "${rem(g.fontSizeHeading3)}", "${rem(g.fontSizeHeading4)}", "${rem(g.fontSizeHeading5)}", "${rem(g.fontSize)}", "${rem(g.fontSize)}"]
headingFontWeights = [${Array(6).fill(g.fontWeightStrong).join(', ')}]
${Object.entries(hues).map(([k, [fg, bg]]) => `${k}Color = "${fg}"\n${k}BackgroundColor = "${bg}"\n${k}TextColor = "${fg}"`).join('\n')}

# Inter for text, JetBrains Mono for code and labels (DESIGN.md section 16). Self-hosted, served from ./static.
[[theme.fontFaces]]
family = "Inter"
url = "app/static/fonts/inter-latin-wght-normal.woff2"
weight = "100 900"
style = "normal"

[[theme.fontFaces]]
family = "JetBrains Mono"
url = "app/static/fonts/jetbrains-mono-latin-wght-normal.woff2"
weight = "100 800"
style = "normal"
`;
fs.mkdirSync(path.join(root, '.streamlit'), { recursive: true });
fs.writeFileSync(path.join(root, '.streamlit', 'config.toml'), toml);

// ---------- CSS bundle ----------
const uiDir = path.join(root, 'ui');
fs.mkdirSync(uiDir, { recursive: true });
const spacing = readText(path.join(__dirname, 'spacing.css'));
// Bundle order: app components, icon masks (generated by gen-icons.js), landing page.
const NL = String.fromCharCode(10);
const components = ['components.css', 'icons.css', 'landing.css', 'signin.css', 'workspace.css', 'neon.css', 'motion.css']
  .map((f) => `/* --- ui/${f} --- */` + NL + readText(path.join(uiDir, f)))
  .join(NL);

// Light block of tokens.css (first :root rule) -> name -> value
const tokensCss = readText(path.join(__dirname, 'tokens', 'tokens.css'));
const lightBlock = tokensCss.slice(tokensCss.indexOf(':root {'), tokensCss.indexOf('\n}\n') + 3);
const lightVars = {};
for (const m of lightBlock.matchAll(/^\s+(--ant-[a-z0-9-]+):\s*([\s\S]*?);\n(?=\s+--|\})/gm)) lightVars[m[1]] = m[2].replace(/\s+/g, ' ').trim();

const used = new Set([...(spacing + components).matchAll(/var\((--ant-[a-z0-9-]+)/g)].map((m) => m[1]));
const missing = [...used].filter((n) => !(n in lightVars));
const tokenBlock =
  ':root {\n' + [...used].filter((n) => n in lightVars).sort().map((n) => `  ${n}: ${lightVars[n]};`).join('\n') + '\n}\n';

const css = `/* GENERATED by design-system/build-ui.js. Edit ui/components.css or design-system/spacing.css, then rebuild.
   Light mode only. ${used.size} of ${Object.keys(lightVars).length} Ant tokens are used. */\n${tokenBlock}\n/* --- spacing.css --- */\n${spacing}\n/* --- ui/components.css --- */\n${components}`;
fs.writeFileSync(path.join(uiDir, 'app.css'), css);

console.log(`config.toml + ui/app.css written (${(css.length / 1024).toFixed(1)} KB, ${used.size} tokens used)`);
report.forEach((r) => console.log(' AA fix:', r));
Object.entries(hues).forEach(([k, [fg, bg]]) =>
  console.log(` ${k}: ${fg} on white ${contrast(fg, bgPage).toFixed(2)}:1, on tint ${contrast(fg, bg).toFixed(2)}:1`));
console.log(' text', text, contrast(text, bgPage).toFixed(2) + ':1', '| secondary', solid(g.colorTextSecondary), contrast(g.colorTextSecondary, bgPage).toFixed(2) + ':1');
if (missing.length) { console.error('UNKNOWN TOKENS:', missing); process.exit(1); }
