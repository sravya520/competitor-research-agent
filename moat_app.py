"""Router for the Streamlit app: global setup, then the page the URL asks for.

Pages live in views/ (landing, tool, account, privacy, terms). Only this file and views/
import Streamlit; the pipeline and backend know nothing about it (CLAUDE.md).
"""

import os
from pathlib import Path

import streamlit as st
from dotenv import load_dotenv

load_dotenv()  # local .env first, so views can check os.environ before config.py imports

# config.py reads GEMINI_API_KEY / TAVILY_API_KEY from os.environ the moment it is imported
# (populated locally via a .env file, which is gitignored and never reaches a deployed server).
# Streamlit Cloud has its own secrets system instead. Bridging st.secrets into os.environ here,
# before views/tool.py imports the pipeline, lets both paths work without config.py (or main.py's
# CLI) ever needing to know Streamlit exists. No secrets.toml at all is fine: the landing and
# legal pages don't need keys.
for _key in ("GEMINI_API_KEY", "TAVILY_API_KEY"):
    try:
        if _key not in os.environ and _key in st.secrets:
            os.environ[_key] = st.secrets[_key]
    except st.errors.StreamlitSecretNotFoundError:
        break

st.set_page_config(
    page_title="Moat",
    page_icon=str(Path(__file__).parent / "static" / "favicon.png"),  # the nav mark: ink square, white check
)

# Design system stylesheet: spacing, targets, focus. Colors/fonts come from
# .streamlit/config.toml. Both are generated by design-system/build-ui.js (DESIGN.md section 13).
st.html(f"<style>{(Path(__file__).parent / 'ui' / 'app.css').read_text(encoding='utf-8')}</style>")

st.navigation(
    [
        st.Page("views/landing.py", title="Moat", default=True),
        st.Page("views/tool.py", title="Moat workspace", url_path="app"),
        st.Page("views/account.py", title="Your account", url_path="account"),
        st.Page("views/privacy.py", title="Privacy Policy", url_path="privacy"),
        st.Page("views/terms.py", title="Terms of Use", url_path="terms"),
    ],
    position="hidden",  # we draw our own header (views/chrome.py)
).run()
